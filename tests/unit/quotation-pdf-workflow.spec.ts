import type { SupabaseClient } from '@supabase/supabase-js';
import { expect, test } from '@playwright/test';
import { createDraftPdfWorkflow } from '../../src/features/quotations/pdf-workflow';
import { draftPdfFixture, pdfFixtureId } from '../helpers/quotation-pdf-fixtures';

function setup(
  options: {
    uploadError?: boolean;
    mismatch?: boolean;
    finishLost?: boolean;
    finishError?: boolean;
    abandonError?: boolean;
    denyDownload?: boolean;
    denyAudit?: boolean;
    externalUrl?: boolean;
  } = {},
) {
  let state = 'pending';
  let metadata: Record<string, unknown> = {};
  let uploaded: Uint8Array = new Uint8Array();
  const calls: string[] = [];
  const id = pdfFixtureId(300);
  const path = `${id}/${pdfFixtureId(301)}.pdf`;
  const record = () => ({ ...metadata, id, path, state });
  const admin = {
    async rpc(_name: string, args: { p_operation: string; p_input: Record<string, unknown> }) {
      const op = args.p_operation;
      calls.push(op);
      if (op === 'reserve') {
        const p = args.p_input;
        metadata = {
          quotationId: p.quotationId,
          version: p.version,
          sha256: p.sha256,
          bytes: p.bytes,
          pages: p.pages,
          template: p.template,
        };
      }
      if (op === 'finish') {
        if (options.finishLost) state = 'ready';
        if (options.finishLost || options.finishError) return { error: { code: 'network' } };
        state = 'ready';
      }
      if (op === 'abandon') {
        if (options.abandonError) return { error: { code: 'network' } };
        if (state !== 'ready') state = 'failed';
      }
      if (
        (op === 'authorize_download' && options.denyDownload) ||
        (op === 'download_issued' && options.denyAudit)
      )
        return { error: { code: '42501' } };
      return { data: record(), error: null };
    },
    storage: {
      from: () => ({
        async upload(_path: string, bytes: Uint8Array, settings: { upsert: boolean }) {
          calls.push('upload');
          uploaded = bytes;
          expect(settings.upsert).toBe(false);
          return { error: options.uploadError ? { message: 'unconfirmed' } : null };
        },
        async download() {
          calls.push('download');
          return { data: new Blob([Buffer.from(options.mismatch ? [1] : uploaded)]), error: null };
        },
        async remove() {
          calls.push('remove');
          return { error: null };
        },
        async createSignedUrl(_path: string, ttl: number, settings: { download: string }) {
          calls.push('sign');
          expect(ttl).toBe(60);
          expect(settings.download.endsWith('.pdf')).toBe(true);
          return {
            error: null,
            data: {
              signedUrl: options.externalUrl
                ? 'https://example.test/file'
                : `http://127.0.0.1:57421/storage/v1/object/sign/crm-quotation-drafts/${path}?token=synthetic`,
            },
          };
        },
      }),
    },
  } as unknown as SupabaseClient;
  return { workflow: createDraftPdfWorkflow(admin, pdfFixtureId(2)), calls, id };
}

test('upload uses generated bytes and repeated ready requests avoid another upload', async () => {
  const { workflow, calls, id } = setup();
  const model = draftPdfFixture();
  expect(await workflow.generate(pdfFixtureId(4), model)).toEqual({ documentId: id });
  await workflow.generate(pdfFixtureId(4), model);
  expect(calls.filter((c) => c === 'upload')).toHaveLength(1);
  expect(calls).not.toContain('remove');
});
test('an unconfirmed upload response verifies the stored bytes before finalization', async () => {
  const { workflow, calls } = setup({ uploadError: true });
  await workflow.generate(pdfFixtureId(4), draftPdfFixture());
  expect(calls).toContain('download');
  expect(calls).toContain('finish');
  expect(calls).not.toContain('remove');
});
test('mismatched retry bytes fail metadata before object cleanup', async () => {
  const { workflow, calls } = setup({ uploadError: true, mismatch: true });
  await expect(workflow.generate(pdfFixtureId(4), draftPdfFixture())).rejects.toMatchObject({
    retryable: false,
  });
  expect(calls.indexOf('abandon')).toBeLessThan(calls.indexOf('remove'));
  expect(calls).not.toContain('finish');
});
test('a lost finalization response never deletes an already ready PDF', async () => {
  const { workflow, calls, id } = setup({ finishLost: true });
  expect(await workflow.generate(pdfFixtureId(4), draftPdfFixture())).toEqual({ documentId: id });
  expect(calls).not.toContain('remove');
});
test('an unknown cleanup outcome retains the private object and the retry ID', async () => {
  const { workflow, calls } = setup({ finishError: true, abandonError: true });
  await expect(workflow.generate(pdfFixtureId(4), draftPdfFixture())).rejects.toMatchObject({
    retryable: true,
  });
  expect(calls).not.toContain('remove');
});
test('download issuance is authorized, signed for 60 seconds and audited in order', async () => {
  const { workflow, calls, id } = setup();
  await workflow.generate(pdfFixtureId(4), draftPdfFixture());
  calls.length = 0;
  const before = Date.now();
  const result = await workflow.download(id);
  expect(calls).toEqual(['authorize_download', 'sign', 'download_issued']);
  expect(result.expiresAt).toBeGreaterThanOrEqual(before + 60000);
  expect(result.expiresAt).toBeLessThanOrEqual(Date.now() + 60000);
});
test('revoked access cannot obtain a signed URL', async () => {
  const { workflow, calls, id } = setup({ denyDownload: true });
  await expect(workflow.download(id)).rejects.toThrow('PDF access is unavailable');
  expect(calls).not.toContain('sign');
});
test('audit rejection prevents returning a prepared URL', async () => {
  const { workflow, id } = setup({ denyAudit: true });
  await workflow.generate(pdfFixtureId(4), draftPdfFixture());
  await expect(workflow.download(id)).rejects.toThrow('PDF access is unavailable');
});
test('external download addresses are rejected', async () => {
  const { workflow, id } = setup({ externalUrl: true });
  await workflow.generate(pdfFixtureId(4), draftPdfFixture());
  await expect(workflow.download(id)).rejects.toThrow('local download address');
});